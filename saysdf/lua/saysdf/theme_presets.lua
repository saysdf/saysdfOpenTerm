-- saysdfTerminal: catalog of color schemes for the menu "View -> Theme" (data only, no side effects).
--
-- GENERATED from the fork's theme research notes (kept outside the published tree):
-- schemes were selected by WCAG contrast; edits go there (table, sources, licenses).
-- Third-party schemes are unchanged: colors are taken as they are, weak schemes are simply left out.
--
-- The module executes nothing on require and has no setup(): saysdf.setup skips it.
--
-- API:
--   presets.groups          - array of groups { id, label, schemes = { <scheme>, ... } }, order = menu order.
--   <scheme>:
--     name      - WezTerm scheme name (the value for config.color_scheme);
--     label     - menu label (a catalog key marked with N_; translated for display by presets.tr);
--     group     - group id ('windows'|'macos'|'ubuntu'|'contrast'|'light'|'dark'|'popular');
--     kind      - 'light' | 'dark' (by background luminance);
--     contrast  - WCAG contrast foreground/background (1..21);
--     ansi_min  - minimum contrast of ANSI colors 1..6 (red..cyan) against the background (informational);
--     source    - source and license (a catalog key marked with N_);
--     colors    - only for schemes that are NOT built into WezTerm: a table in the WezTerm
--                 color scheme format (foreground, background, cursor_bg, cursor_fg, cursor_border,
--                 selection_fg, selection_bg, ansi[8], brights[8]). Built-in schemes have nil.
--   presets.list()           - flat array of all schemes in menu order.
--   presets.find(name)       - the scheme by name, or nil.
--   presets.schemes_table()  - { [name] = colors } for the non-built-in schemes (fresh copies of the tables).
--   presets.tr(key)          - translation of a label/group name for display (catalog ru/theme_presets.toml).
--
-- Registration of the non-built-in schemes (done by saysdf.theme, not by this module):
--   config.color_schemes = config.color_schemes or {}
--   for name, colors in pairs(presets.schemes_table()) do
--     if config.color_schemes[name] == nil then config.color_schemes[name] = colors end
--   end
--   config.color_scheme = 'Campbell (Windows Terminal)'
-- (Names of non-built-in schemes carry a source suffix so they do not clash with built-in ones.)

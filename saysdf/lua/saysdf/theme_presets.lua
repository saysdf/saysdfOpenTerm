local function copy(t)
  local r = {}
  for k, v in pairs(t) do
    r[k] = type(v) == "table" and copy(v) or v
  end
  return r
end

function M.list()
  local out = {}
  for _, g in ipairs(M.groups) do
    for _, s in ipairs(g.schemes) do
      out[#out + 1] = s
    end
  end
  return out
end

function M.find(name)
  for _, g in ipairs(M.groups) do
    for _, s in ipairs(g.schemes) do
      if s.name == name then
        return s
      end
    end
  end
  return nil
end

function M.schemes_table()
  local out = {}
  for _, g in ipairs(M.groups) do
    for _, s in ipairs(g.schemes) do
      if s.colors then
        out[s.name] = copy(s.colors)
      end
    end
  end
  return out
end

return M
